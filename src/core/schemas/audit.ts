import { z } from 'zod';
export const AuditEventSchema = z.object({
  schemaVersion: z.literal(1),
  id: z.uuid(),
  analysisId: z.uuid(),
  issueId: z.string().nullable(),
  at: z.iso.datetime(),
  actor: z.enum(['human', 'model', 'system']),
  action: z.enum([
    'create_analysis',
    'confirm',
    'dismiss',
    'reopen',
    'edit_span',
    'edit_label',
    'edit_severity',
    'import',
    'delete_analysis',
    'create_revision',
    'apply_revision',
    'create_generation',
    'accept_generation',
    'import_paper',
    'delete_paper',
  ]),
  before: z.unknown().nullable(),
  after: z.unknown().nullable(),
  note: z.string().nullable(),
});
export type AuditEvent = z.infer<typeof AuditEventSchema>;
