import type { StoredCorpusProfile } from '../schemas/corpusProfile';
import {
  ExportPackageSchema,
  type Analysis,
  type AuditEvent,
  type Revision,
  type Generation,
  type Paper,
  type PaperOverviewRecord,
  type PaperChecksRecord,
  type PaperReviewsRecord,
  type PaperProbesRecord,
  type CalibrationLabelSet,
  type MeasurementsRecord,
  type LibraryItem,
  type PaperInsightsRecord,
  type ExtractionProject,
  type Corpus,
  type StanceRecord,
} from '../schemas';
export function buildExportPackage(
  analyses: Analysis[],
  auditEvents: AuditEvent[],
  appVersion: string,
  now: Date,
  revisions: Revision[] = [],
  generations: Generation[] = [],
  papers: Paper[] = [],
  paperOverviews: PaperOverviewRecord[] = [],
  paperChecks: PaperChecksRecord[] = [],
  paperReviews: PaperReviewsRecord[] = [],
  paperProbes: PaperProbesRecord[] = [],
  calibrationLabels: CalibrationLabelSet[] = [],
  measurements: MeasurementsRecord[] = [],
  library: LibraryItem[] = [],
  stance: StanceRecord[] = [],
  paperInsights: PaperInsightsRecord[] = [],
  extractionProjects: ExtractionProject[] = [],
  corpora: Corpus[] = [],
  corpusProfiles: StoredCorpusProfile[] = [],
) {
  return ExportPackageSchema.parse({
    format: 'paragraph-lab-export',
    formatVersion: 1,
    exportedAt: now.toISOString(),
    appVersion,
    analyses,
    auditEvents,
    revisions,
    generations,
    papers,
    paperOverviews,
    paperChecks,
    paperReviews,
    paperProbes,
    calibrationLabels,
    measurements,
    library,
    stance,
    paperInsights,
    extractionProjects,
    corpora,
    corpusProfiles,
  });
}
